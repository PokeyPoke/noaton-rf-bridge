#!/usr/bin/env python3
"""Generate the ESPHome bridge config and its web page from home.json.

    python3 tools/gen_esphome.py && esphome run esphome/rf-bridge.yaml

Writes esphome/rf-bridge.yaml and esphome/ui.js (from esphome/ui.src.js).
Rooms, their remote and wall-switch codes, pins, timezone and away-mode
windows come from home.json (see home.example.json). Edit that, not the outputs.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME = os.path.join(ROOT, "home.json")
OUT = os.path.join(ROOT, "esphome", "rf-bridge.yaml")
UI_SRC = os.path.join(ROOT, "esphome", "ui.src.js")
UI_OUT = os.path.join(ROOT, "esphome", "ui.js")

SCHEDULES = 8

# The 9-bit button field after a Noaton remote's 20-bit device ID. Every
# remote sends the same fields; only the device ID differs.
BUTTONS = [("Power", "110010001"), ("Breeze / natural wind", "100001011"),
           ("Fan speed 1", "111101000"), ("Fan speed 2", "111001000"),
           ("Fan speed 3", "110101001"), ("Fan speed 4", "110001001"),
           ("Fan speed 5", "101101010"), ("Fan speed 6", "101001010"),
           ("F/R reverse", "100101011"), ("Timer 1H", "010010101"),
           ("Timer 4H", "001110110"), ("Timer 8H", "101010010"),
           ("Light cool (blue)", "110110001"), ("Light warm (yellow)", "101110010"),
           ("Light neutral (white)", "111010000"), ("LED brighter", "100110011"),
           ("LED dimmer", "011110100"), ("Light toggle", "010110101")]


def minutes(hhmm):
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


def load_home(path=HOME):
    if not os.path.exists(path):
        raise SystemExit(f"{os.path.relpath(path, ROOT)} not found: copy home.example.json and fill it in")
    with open(path) as fh:
        home = json.load(fh)
    for room in home["rooms"]:
        code = room["remote"]
        if len(code) != 20 or set(code) - {"0", "1"}:
            raise SystemExit(f"{room['name']}: remote must be the 20-bit device ID, got {code!r}")
        for gang, code in room.get("switch", {}).items():
            if gang not in ("fan", "light") or len(code) != 24 or set(code) - {"0", "1"}:
                raise SystemExit(f"{room['name']}: switch needs 24-bit fan/light codes, got {gang}={code!r}")
    return home

HEADER = """\
# GENERATED by tools/gen_esphome.py from the code table -- edit that, not this.
#
# ESP32-C3 SuperMini RF bridge. Wall switches and schedules run on the device,
# so they keep working without a phone; the page at http://rf-bridge.local is
# esphome/ui.js, served by the device itself. `api` is kept so Home Assistant
# can adopt it later.

esphome:
  name: rf-bridge
  friendly_name: RF Bridge
  includes:
    - noaton.h
  on_boot:
    # After restored fan and light states are published, so a reboot transmits nothing.
    priority: -100
    then:
      - lambda: |-
          noaton::transmitter() = id(rf_tx);
          noaton::fan_lock() = id(fans_disabled);
          noaton::away() = id(away_mode);
          noaton::rooms() = {{
{rooms}
          }};
          noaton::away_windows() = {{
{away}
          }};
          noaton::quiet() = false;

esp32:
  board: esp32-c3-devkitm-1
  framework:
    type: esp-idf

logger:

wifi:
  ssid: !secret wifi_ssid
  password: !secret wifi_password
  # Many C3 SuperMini boards have a poor antenna match and drop WiFi at full power.
  output_power: 8.5dB
  ap:
    ssid: RF Bridge Fallback
    password: !secret fallback_password

captive_portal:

api:
  # No Home Assistant yet; without this the device reboots every 15 minutes
  # waiting for one.
  reboot_timeout: 0s

ota:
  - platform: esphome
    password: !secret ota_password

web_server:
  version: 3
  # Our own page, served from flash: no default UI and nothing from the internet.
  js_url: ""
  js_include: ui.js

time:
  - platform: sntp
    id: sntp_time
    timezone: {tz}
    on_time:
      - seconds: 0
        then:
          - lambda: |-
              auto now = id(sntp_time).now();
              if (!now.is_valid()) return;
              int day = (now.day_of_week + 5) % 7;  // ESPHome: 1 = Sunday; slots: 0 = Monday
{ticks}
              noaton::away_tick(now.hour, now.minute, now.day_of_year);

remote_transmitter:
  id: rf_tx
  pin: {tx}
  carrier_duty_percent: 100%
  # Blocking: a send is ~0.2s, and two quick presses must not overlap on air.
  non_blocking: false

remote_receiver:
  id: rf_rx
  pin: {rx}
  dump: []
  # Shorter than either device's frame gap (switch 9.3ms, remote >=5.2ms) and
  # longer than any in-frame low (~1.1ms), so one packet is one frame.
  idle: 4ms
  on_raw:
    then:
      - lambda: |-
          std::string code = noaton::decode(x);
          if (!code.empty() && !noaton::own_echo(code)) noaton::frame(code);

interval:
  # Acts on each press once its button is released (see noaton::frame).
  - interval: 50ms
    then:
      - lambda: |-
          auto handle = [&](const std::string &code) {{
{dispatch}
          }};
          for (auto &press : noaton::released()) {{
            // A switch frame has no check bits, and in noise a lone misread copy
            // can turn up; a real press always repeats, so wait for a second copy.
            bool lone = press.code.size() == 24 && press.frames < 2;
            // One line per press; `esphome logs` over WiFi shows what the bridge hears.
            ESP_LOGI("rf", "heard %u bits: %s (%u frames)%s", (unsigned) press.code.size(),
                     press.code.c_str(), (unsigned) press.frames, lone ? " - ignored, single copy" : "");
            if (!lone) handle(press.code);
          }}
  # Sends due steps of a running sequence (dimmest, wake-up), one per tick.
  - interval: 100ms
    then:
      - lambda: noaton::pump();
  - interval: 5s
    then:
      - lambda: |-
          auto &st = noaton::rx_stats();
          ESP_LOGI("rf", "rx last 5s: %u packets, %u frame-sized, %u decoded",
                   (unsigned) st.packets, (unsigned) st.frame_sized, (unsigned) st.decoded);
          st = noaton::RxStats();

text_sensor:
  - platform: template
    name: Sequence
    update_interval: 1s
    lambda: return noaton::pending();
  - platform: template
    name: Clock
    update_interval: 20s
    lambda: |-
      auto now = id(sntp_time).now();
      if (!now.is_valid()) return std::string("not synced");
      return now.strftime("%a %H:%M");

text:
  # The page's one write path: "<rooms>|<button field or sequence>|<nonce>".
  - platform: template
    name: Command
    mode: text
    max_length: 32
    optimistic: true
    on_value:
      - lambda: noaton::command(x);
{schedules}
"""


def main():
    home = load_home()
    bridge = home["bridge"]
    buttons = [{"name": n, "field": f} for n, f in BUTTONS]

    room_init, away, dispatch, fans, lights, names = [], [], [], [], [], []
    for n, room in enumerate(home["rooms"]):
        rid, name, id20 = f"room{n + 1}", room["name"], room["remote"]
        fan_id, light_id = f"{rid}_fan", f"{rid}_light"
        names.append(name)

        room_init.append(f'            {{"{id20}", id({fan_id}), id({light_id})}},  // {name}')
        win = room.get("away")
        span = [minutes(t) for t in win["on"] + win["off"]] if win else [-1] * 4
        away.append(f"            {{{', '.join(map(str, span))}}},  // {name}")
        for gang, code in room.get("switch", {}).items():
            act = (f"noaton::fan_gang({n});" if gang == "fan"
                   else f"noaton::press({n}, noaton::kLightToggle);")
            dispatch.append(f'            if (code == "{code}") {{ {act} return; }}'
                            f"  // {name} wall switch -> {gang}")
        dispatch.append(f'            if (code.size() == 30 && code.compare(0, 20, "{id20}") == 0) {{'
                        f" noaton::heard({n}, code.substr(20, 9)); return; }}"
                        f"  // {name} handheld remote")
        fans.append(f"""\
  - platform: template
    id: {fan_id}
    name: {name} Fan
    speed_count: 6
    restore_mode: RESTORE_DEFAULT_OFF
    on_state:
      - lambda: noaton::apply(id(rf_tx), "{id20}", x);""")
        # A record, not a reading: kept from the bridge's own presses, the wall
        # switch and the overheard remote. Turning it on/off sends Toggle only
        # if the record differs.
        lights.append(f"""\
  - platform: template
    id: {light_id}
    name: {name} Light
    optimistic: true
    restore_mode: RESTORE_DEFAULT_OFF
    turn_on_action:
      - lambda: noaton::light_action({n}, true);
    turn_off_action:
      - lambda: noaton::light_action({n}, false);""")

    schedules = "\n".join(f"""\
  - platform: template
    id: schedule_{i}
    name: Schedule {i}
    mode: text
    max_length: 40
    optimistic: true
    restore_value: true
    initial_value: \"\"""" for i in range(1, SCHEDULES + 1))
    ticks = "\n".join(f"              noaton::schedule_tick(id(schedule_{i}).state, now.hour, now.minute, day);"
                      for i in range(1, SCHEDULES + 1))

    yaml = HEADER.format(rooms="\n".join(room_init), away="\n".join(away), tz=bridge["timezone"],
                         ticks=ticks, rx=bridge["rx_pin"], tx=bridge["tx_pin"],
                         dispatch="\n".join(dispatch), schedules=schedules)
    yaml += "\nfan:\n" + "\n".join(fans) + "\n"
    # The page's "Disable all fans"; see noaton::fan_lock.
    lights.append("""\
  - platform: template
    id: fans_disabled
    name: Fans Disabled
    optimistic: true
    restore_mode: RESTORE_DEFAULT_OFF""")
    # Lights on and off through the evening while nobody is in; see noaton::away_tick.
    lights.append("""\
  - platform: template
    id: away_mode
    name: Away Mode
    optimistic: true
    restore_mode: RESTORE_DEFAULT_OFF""")
    yaml += "\nswitch:\n" + "\n".join(lights) + "\n"
    with open(OUT, "w") as fh:
        fh.write(yaml)

    wins = [r["away"] for r in home["rooms"] if r.get("away")]
    away_span = f"{min(w['on'][0] for w in wins)}–{max(w['off'][1] for w in wins)}" if wins else ""
    config = {"rooms": names, "buttons": buttons, "schedules": SCHEDULES, "away": away_span}
    with open(UI_SRC) as fh:
        ui = fh.read()
    with open(UI_OUT, "w") as fh:
        fh.write("// GENERATED by tools/gen_esphome.py from ui.src.js -- edit that, not this.\n")
        fh.write(ui.replace("/*CONFIG*/null", json.dumps(config)))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(fans)} rooms, {SCHEDULES} schedules)"
          f" and {os.path.relpath(UI_OUT, ROOT)} ({len(buttons)} buttons)")


if __name__ == "__main__":
    main()
